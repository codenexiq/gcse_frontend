"use client";

import { useEffect, useState } from "react";
import MathText from "@/components/ui/MathText";
import { ApiError } from "@/lib/api";
import { cloneBlock, parsePasted, toBase64 } from "@/lib/lessons";
import { aiPdf, aiQuiz, questionBank, type BankQuestion } from "@/services/lessonService";
import type { LessonBlock, LessonStrand, TutorLesson } from "@/types";
import styles from "./QuizMaker.module.css";

type Mode = "bank" | "ai" | "pdf" | "paste";

interface Props {
  topic: string;
  strands: LessonStrand[];
  startMode: "ai" | "pdf";
  /** Saves the questions as a new lesson (hidden from students) and returns it. */
  makeLesson: (title: string, blocks: LessonBlock[]) => Promise<TutorLesson>;
  onClose: () => void;
  onCreated: (lesson: TutorLesson, note: string) => void;
}

const MODES: { key: Mode; label: string; time: string }[] = [
  { key: "bank", label: "From the question bank", time: "About 1 minute" },
  { key: "ai", label: "Generate with AI", time: "About 3 minutes" },
  { key: "pdf", label: "From a PDF", time: "About 2 minutes" },
  { key: "paste", label: "Paste your own", time: "About 5 minutes" },
];
const MAX_PDF = 7 * 1024 * 1024;
const off = (err: unknown) => err instanceof ApiError && err.status === 503;

/** The quiz maker (prototype): a quiz from the question bank, generated by AI, made from a PDF, or pasted. The result is a new lesson the tutor checks before showing it to students. */
export default function QuizMaker({ topic: startTopic, strands, startMode, makeLesson, onClose, onCreated }: Props) {
  const [mode, setMode] = useState<Mode>(startMode);
  const [topic, setTopic] = useState(startTopic);
  const [tier, setTier] = useState("Higher");
  const [count, setCount] = useState(8);
  const [mix, setMix] = useState("mixed");
  const [focus, setFocus] = useState("");
  const [paste, setPaste] = useState("");
  const [allTopics, setAllTopics] = useState(false);
  const [bank, setBank] = useState<BankQuestion[] | null>(null);
  const [picked, setPicked] = useState<Set<string>>(new Set());
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");

  useEffect(() => {
    if (mode !== "bank") return;
    let live = true;
    setBank(null);
    questionBank(allTopics ? null : topic)
      .then((list) => live && setBank(list))
      .catch(() => live && setBank([]));
    return () => {
      live = false;
    };
  }, [mode, topic, allTopics]);

  async function finish(blocks: LessonBlock[], note = "") {
    if (blocks.length === 0) return setError(note || "No questions were made. Try again or choose another way.");
    const lesson = await makeLesson(`Quiz: ${topic}`, blocks);
    onCreated(lesson, `${blocks.length} question${blocks.length === 1 ? "" : "s"} ready. Check each answer, then tick Visible to students.${note ? ` ${note}` : ""}`);
  }

  async function run(label: string, work: () => Promise<void>) {
    setError("");
    setBusy(label);
    try {
      await work();
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong. Try again.");
    } finally {
      setBusy("");
    }
  }

  async function fromBank() {
    const list = (await questionBank(null)).filter((q) => picked.has(q.block.id));
    await finish(list.map((q) => cloneBlock(q.block)));
  }

  async function fromAi() {
    let blocks: LessonBlock[] = [];
    let note = "";
    try {
      blocks = (await aiQuiz({ topic, tier, n: count, mix, focus })).blocks;
    } catch (err) {
      if (!off(err)) throw err;
      // No AI: use questions already in the library, as the prototype does.
      blocks = (await questionBank(topic)).slice(0, count).map((q) => cloneBlock(q.block));
      note = blocks.length ? "The AI helper is not switched on, so these come from the question bank." : "The AI helper is not switched on and there are no questions on this topic yet. Try the question bank or paste your own.";
    }
    await finish(blocks, note);
  }

  async function fromPdf(file: File | undefined) {
    if (!file) return;
    if (file.size > MAX_PDF) return setError("That PDF is over 7 MB. Try a shorter one.");
    await run("Reading the PDF and writing questions. This can take a minute...", async () => {
      try {
        await finish((await aiPdf({ topic, mode: "quiz", pdf: await toBase64(file) })).blocks);
      } catch (err) {
        if (off(err)) throw new Error("The AI helper is not switched on yet, so it cannot read PDFs. Paste your questions instead.");
        throw err;
      }
    });
  }

  async function fromPaste() {
    if (!paste.trim()) return setError("Paste at least one question first.");
    await finish(parsePasted(paste));
  }

  const topicSelect = (
    <label className={styles.field}>
      Topic
      <select value={topic} onChange={(e) => setTopic(e.target.value)}>
        {strands.map((s) => (
          <optgroup key={s.name} label={s.name}>
            {s.topics.map((t) => <option key={t.name}>{t.name}</option>)}
          </optgroup>
        ))}
      </select>
    </label>
  );

  return (
    <section className={styles.card} aria-labelledby="qm-title">
      <div className={styles.between}>
        <div>
          <span className={styles.label}>Create a quiz</span>
          <h2 id="qm-title" className={styles.h2}>New quiz</h2>
        </div>
        <button type="button" className={styles.ghost} onClick={onClose}>Close</button>
      </div>

      <div className={styles.modes} role="group" aria-label="How to create the quiz">
        {MODES.map((m) => (
          <button key={m.key} type="button" className={styles.mode} aria-pressed={mode === m.key} onClick={() => { setMode(m.key); setError(""); }}>
            <strong>{m.label}</strong>
            <span>{m.time}</span>
          </button>
        ))}
      </div>

      {mode === "bank" && (
        <>
          <div className={styles.grid}>
            {topicSelect}
            <label className={styles.choice}><input type="checkbox" checked={allTopics} onChange={(e) => setAllTopics(e.target.checked)} /> Show every topic</label>
          </div>
          {bank === null ? (
            <p className={styles.muted} role="status">Loading questions...</p>
          ) : bank.length === 0 ? (
            <p className={styles.muted}>No questions on {topic} yet. Try <button type="button" className={styles.link} onClick={() => setMode("ai")}>Generate with AI</button>, or tick &ldquo;Show every topic&rdquo;.</p>
          ) : (
            <ul className={styles.bank}>
              {bank.map((q) => (
                <li key={q.block.id}>
                  <label>
                    <input
                      type="checkbox"
                      checked={picked.has(q.block.id)}
                      onChange={(e) => setPicked((old) => { const next = new Set(old); if (e.target.checked) next.add(q.block.id); else next.delete(q.block.id); return next; })}
                    />
                    <span className={styles.stack}>
                      <span>{"question" in q.block && <MathText text={q.block.question} />}</span>
                      <span className={styles.small}>{q.block.type === "mcq" ? "Multiple choice" : `Written · ${q.block.type === "written" ? q.block.marks : 0} marks`} · {q.topic} · from {q.source}</span>
                    </span>
                  </label>
                </li>
              ))}
            </ul>
          )}
          <div className={styles.row}>
            <button type="button" className={`${styles.btn} ${styles.primary}`} disabled={picked.size === 0 || Boolean(busy)} onClick={() => void run("Creating the quiz...", fromBank)}>
              Create quiz with {picked.size} question{picked.size === 1 ? "" : "s"}
            </button>
            <span className={styles.small}>Every question in a lesson or quiz is added to the bank.</span>
          </div>
        </>
      )}

      {mode === "ai" && (
        <>
          <div className={styles.grid}>
            {topicSelect}
            <label className={styles.field}>Tier<select value={tier} onChange={(e) => setTier(e.target.value)}><option>Higher</option><option>Foundation</option></select></label>
            <label className={styles.field}>Questions<select value={count} onChange={(e) => setCount(Number(e.target.value))}>{[5, 8, 10].map((n) => <option key={n}>{n}</option>)}</select></label>
            <label className={styles.field}>
              Question types
              <select value={mix} onChange={(e) => setMix(e.target.value)}>
                <option value="mcq">All multiple choice</option>
                <option value="mixed">Multiple choice + 1 written</option>
                <option value="written">Mostly written (exam-style)</option>
              </select>
            </label>
          </div>
          <label className={styles.field}>
            <span>Anything to focus on? <span className={styles.hint}>Optional, e.g. &ldquo;questions with negative numbers&rdquo;</span></span>
            <input type="text" maxLength={200} value={focus} onChange={(e) => setFocus(e.target.value)} />
          </label>
          <div className={styles.row}>
            <button type="button" className={`${styles.btn} ${styles.primary}`} disabled={Boolean(busy)} onClick={() => void run("Writing questions...", fromAi)}>{busy ? "Writing questions..." : "Generate quiz"}</button>
            <span className={styles.small}>Original exam-style questions, not copied from past papers. You check every answer before students see it.</span>
          </div>
        </>
      )}

      {mode === "pdf" && (
        <>
          <div className={styles.grid}>{topicSelect}</div>
          <p className={styles.muted}>Upload a PDF worksheet or notes (up to 7 MB). The AI keeps your questions, or writes new ones from your notes, and you check them before students see the quiz.</p>
          <div className={styles.row}>
            <input id="qm-pdf" className={styles.hidden} type="file" accept="application/pdf,.pdf" disabled={Boolean(busy)} onChange={(e) => { void fromPdf(e.target.files?.[0]); e.target.value = ""; }} />
            <label htmlFor="qm-pdf" className={`${styles.btn} ${styles.primary}`}>Choose a PDF</label>
          </div>
        </>
      )}

      {mode === "paste" && (
        <>
          <div className={styles.grid}>{topicSelect}</div>
          <label className={styles.field}>
            <span>Paste your questions <span className={styles.hint}>One question per block, with a blank line between. Mark the answer with &ldquo;Answer:&rdquo;.</span></span>
            <textarea rows={10} value={paste} onChange={(e) => setPaste(e.target.value)} placeholder={"Work out 3/4 + 1/6\nA) 4/10\nB) 11/12\nC) 4/24\nD) 1/2\nAnswer: B\n\nSolve 2x + 5 = 17\nA) 6\nB) 11\nC) 8.5\nD) 24\nAnswer: A"} />
          </label>
          <div className={styles.row}>
            <button type="button" className={`${styles.btn} ${styles.primary}`} disabled={Boolean(busy)} onClick={() => void run("Reading questions...", fromPaste)}>Turn into a quiz</button>
            <span className={styles.small}>Only paste questions you wrote yourself.</span>
          </div>
        </>
      )}

      {busy && mode !== "ai" && <p className={styles.small} role="status">{busy}</p>}
      {error && <p className={styles.error} role="alert">{error}</p>}
    </section>
  );
}
